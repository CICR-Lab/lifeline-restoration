function z = safeProduct(a, b)

z = NaN;

if isfinite(a) && isfinite(b)
    z = a * b;
end

end

function z = safeRatio(num, den)

z = NaN;

if isfinite(num) && ...
        isfinite(den) && ...
        den > 0

    z = num / den;
end

end

function [Lrest, eta90, eta95] = computeLossMetrics(C, peakTime, Dmax, tau90, tau95, tau100)
recoverTol = 1e-8;
Lrest = NaN;
eta90 = NaN;
eta95 = NaN;
if ~(isfinite(peakTime) && isfinite(Dmax) && Dmax > 0 && isfinite(tau100) && tau100 >= 0)
    return;
end

[t, r] = curveToVectors(C);
tau = t - peakTime;
[tauUse, rUse, ok] = curveOnWindow(tau, r, 0, tau100, recoverTol);
if ~ok
    return;
end

dUse = Dmax .* (1 - rUse);
Lrest = trapz(tauUse, dUse);
if ~(isfinite(Lrest) && Lrest > 0)
    Lrest = NaN;
    return;
end

eta90 = tailFraction(tau, r, Dmax, tau90, tau100, Lrest, recoverTol);
eta95 = tailFraction(tau, r, Dmax, tau95, tau100, Lrest, recoverTol);
end

function frac = tailFraction(tau, r, Dmax, tauLo, tauHi, Lrest, recoverTol)
frac = NaN;
if ~(isfinite(tauLo) && isfinite(tauHi) && tauHi >= tauLo && isfinite(Lrest) && Lrest > 0)
    return;
end
[tauUse, rUse, ok] = curveOnWindow(tau, r, tauLo, tauHi, recoverTol);
if ~ok
    return;
end
loss = trapz(tauUse, Dmax .* (1 - rUse));
frac = loss / Lrest;
if isfinite(frac) && (frac < -recoverTol || frac > 1 + recoverTol)
    error("Late-loss fraction outside [0,1]: %.15g", frac);
end
end


function [tUse, rUse, ok] = curveOnWindow(t, r, t0, t1, recoverTol)
ok = false;
tUse = [];
rUse = [];
if isempty(t) || isempty(r) || t0 < min(t) - recoverTol || t1 > max(t) + recoverTol
    return;
end
[r0, ok0] = valueAtOrInterpolate(t, r, t0, recoverTol);
[r1, ok1] = valueAtOrInterpolate(t, r, t1, recoverTol);
if ~(ok0 && ok1)
    return;
end
mask = t > t0 + recoverTol & t < t1 - recoverTol;
tUse = [t0; t(mask); t1];
rUse = [r0; r(mask); r1];
ok = numel(tUse) >= 2;
end

function [vq, ok] = valueAtOrInterpolate(t, y, tq, recoverTol)
vq = NaN;
ok = false;
idx = find(abs(t - tq) <= recoverTol, 1, "first");
if ~isempty(idx)
    vq = y(idx);
    ok = true;
    return;
end
left = find(t < tq, 1, "last");
right = find(t > tq, 1, "first");
if isempty(left) || isempty(right) || t(right) == t(left)
    return;
end
vq = y(left) + (tq - t(left)) * (y(right) - y(left)) / (t(right) - t(left));
ok = isfinite(vq);
end

function [t, r] = curveToVectors(C)
t = [];
r = [];
if isempty(C)
    return;
end
if isstruct(C)
    if ~isfield(C, "day") || ~isfield(C, "value")
        return;
    end
    t = double([C.day]');
    r = double([C.value]');
else
    return;
end
mask = isfinite(t) & isfinite(r);
t = t(mask);
r = r(mask);
if isempty(t)
    return;
end
[t, idx] = sort(t);
r = r(idx);
if any(diff(t) == 0)
    error("Restoration-ratio curve contains duplicate day values.");
end
end

function v = getNumericField(s, name)
v = NaN;
if isfield(s, name)
    x = s.(name);
    if isnumeric(x) || islogical(x)
        if ~isempty(x), v = double(x(1)); end
    else
        v = str2double(string(x));
    end
end
end

function v = getStringField(s, name)
v = "";
if isfield(s, name)
    x = s.(name);
    if isstring(x) || ischar(x) || iscategorical(x)
        sx = string(x);
        if ~isempty(sx) && ~ismissing(sx(1)), v = sx(1); end
    elseif isnumeric(x) && ~isempty(x)
        v = string(x(1));
    end
end
end

function s = normalizeSystemName(s)
s = string(s);
sl = lower(strtrim(s));
s(sl == "e" | sl == "power") = "Power";
s(sl == "w" | sl == "water") = "Water";
s(sl == "g" | sl == "gas") = "Gas";
end

function ensureDir(d)
if ~isfolder(d)
    mkdir(char(d));
end
end

