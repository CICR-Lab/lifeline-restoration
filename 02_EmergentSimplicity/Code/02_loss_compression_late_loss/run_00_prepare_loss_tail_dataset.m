    tau50 = getNumericField(rec, "tau50");
    T90 = getNumericField(rec, "T90");
    tau90 = getNumericField(rec, "tau90");
    T95 = getNumericField(rec, "T95");
    tau95 = getNumericField(rec, "tau95");
    T100 = getNumericField(rec, "T100");
    tau100 = getNumericField(rec, "tau100");

