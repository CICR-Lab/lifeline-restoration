            Lrest, ...
            safeProduct(Dmax, tau95));

    rows{i} = table( ...
        record_ID, ...
        getNumericField(rec, "event_ISO_ID"), ...
        getNumericField(rec, "event_ID"), ...
        getStringField(rec, "Country"), ...
        getStringField(rec, "ISO"), ...
        getStringField(rec, "IncomeGroup"), ...
        getStringField(rec, "OccTime"), ...
        getNumericField(rec, "magnitude"), ...
        getNumericField(rec, "regionIndex"), ...
        getStringField(rec, "regionName"), ...
        normalizeSystemName(getStringField(rec, "System")), ...
        getNumericField(rec, "avg_PGA"), ...
        getNumericField(rec, "popDensity_km2"), ...
        peakTime, ...
        Dmax, ...
        D0, ...
        getNumericField(rec, "nRestorationRatioPoints"), ...
        getNumericField(rec, "nUniqueRestorationValues"), ...
        T50, ...
        tau50, ...
        T90, ...
        tau90, ...
        T95, ...
        tau95, ...
        T100, ...
        tau100, ...
        Lrest, ...
        eta90, ...
        eta95, ...
        Dmax_tau50, ...
        Lrest_over_D0_tau50, ...
        Lrest_over_Dmax_tau50, ...
        Lrest_over_Dmax_tau90, ...
        Lrest_over_Dmax_tau95, ...
        'VariableNames', { ...
            'record_ID', ...
            'event_ISO_ID', ...
            'event_ID', ...
            'Country', ...
            'ISO', ...
            'IncomeGroup', ...
            'OccTime', ...
            'magnitude', ...
            'regionIndex', ...
