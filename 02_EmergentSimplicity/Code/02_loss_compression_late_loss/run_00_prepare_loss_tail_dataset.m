        computeLossMetrics( ...
            rec.restorationratioCurve, ...
            peakTime, ...
            Dmax, ...
            tau90, ...
            tau95, ...
            tau100);

    Dmax_tau50 = safeProduct(Dmax, tau50);

    Lrest_over_D0_tau50 = ...
        safeRatio( ...
            Lrest, ...
            safeProduct(D0, tau50));

    Lrest_over_Dmax_tau50 = ...
        safeRatio( ...
            Lrest, ...
            Dmax_tau50);

