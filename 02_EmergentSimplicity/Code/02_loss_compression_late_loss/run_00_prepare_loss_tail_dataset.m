function run_00_prepare_loss_tail_dataset()


minPreparationPoints = 5;


scriptDir = string(fileparts(mfilename("fullpath")));
moduleRoot = scriptDir;
emergentSimplicityRoot = string(fileparts(fileparts(moduleRoot)));
analysisRoot = string(fileparts(emergentSimplicityRoot));

intermediateRoot = fullfile( ...
    emergentSimplicityRoot, ...
    "outputs", ...
    "intermediate");

inputMat = fullfile( ...
    intermediateRoot, ...
    "01_restoration_shape_phase_ratio", ...
    "unique3_records.mat");

outputRoot = fullfile( ...
    intermediateRoot, ...
    "02_loss_compression_late_loss");

outMat = fullfile( ...
    outputRoot, ...
    "loss_tail_dataset.mat");

ensureDir(outputRoot);

fprintf("Module root:\n%s\n\n", moduleRoot);
fprintf("Input restoration-shape dataset:\n%s\n\n", inputMat);
fprintf("Output MAT:\n%s\n\n", outMat);


if ~isfile(inputMat)
    error("Input MAT not found:\n%s", inputMat);
end

S = load(inputMat, "unique3Records");

if ~isfield(S, "unique3Records")
    error("Input MAT must contain unique3Records:\n%s", inputMat);
end

curves = S.unique3Records;

if isempty(curves)
    error("unique3Records is empty:\n%s", inputMat);
end

requiredFields = [ ...
    "record_ID", ...
    "System", ...
    "restorationratioCurve", ...
    "nRestorationRatioPoints", ...
    "nUniqueRestorationValues", ...
    "PeakTime", ...
    "PeakOutageFraction", ...
    "D0", ...
    "T50", ...
    "tau50", ...
    "T90", ...
    "tau90", ...
    "T95", ...
    "tau95", ...
    "T100", ...
    "tau100"];

missingFields = requiredFields(~isfield(curves, cellstr(requiredFields)));

if ~isempty(missingFields)
    error("unique3Records is missing required field(s): %s", ...
        strjoin(missingFields, ", "));
end


pointCounts = double([curves.nRestorationRatioPoints]);

curves = curves( ...
    isfinite(pointCounts) & ...
    pointCounts >= minPreparationPoints);

if isempty(curves)
    error( ...
        "No records have at least %d restoration-ratio points.", ...
        minPreparationPoints);
end

LossTailRecords = buildLossTailRecords(curves);

requiredOutputFields = [ ...
    "record_ID", ...
    "System", ...
    "nRestorationRatioPoints", ...
    "Dmax", ...
    "D0", ...
    "tau50", ...
    "tau90", ...
    "tau95", ...
    "tau100", ...
    "Lrest", ...
    "eta90", ...
    "eta95", ...
    "Dmax_tau50", ...
    "Lrest_over_D0_tau50", ...
    "Lrest_over_Dmax_tau50", ...
    "Lrest_over_Dmax_tau90", ...
    "Lrest_over_Dmax_tau95"];

missingOutputFields = requiredOutputFields( ...
    ~ismember( ...
        requiredOutputFields, ...
        string(LossTailRecords.Properties.VariableNames)));

if ~isempty(missingOutputFields)
    error( ...
        "Prepared LossTailRecords is missing required output field(s): %s", ...
        strjoin(missingOutputFields, ", "));
end

save(outMat, "LossTailRecords");

fprintf("Prepared loss-tail dataset:\n%s\n", outMat);

preparedPointCounts = ...
    double(LossTailRecords.nRestorationRatioPoints);

fprintf([ ...
    'Prepared cohort: >=%d restoration-ratio points and ', ...
    '>=3 distinct restoration values\n'], ...
    minPreparationPoints);

fprintf([ ...
    'Rows >=%d: %d | Rows >=6: %d\n'], ...
    minPreparationPoints, ...
    height(LossTailRecords), ...
    nnz(isfinite(preparedPointCounts) & preparedPointCounts >= 6));

fprintf([ ...
    'Lrest-valid: %d | ', ...
    'eta90-valid: %d | eta95-valid: %d\n'], ...
    nnz(isfinite(LossTailRecords.Lrest)), ...
    nnz(isfinite(LossTailRecords.eta90)), ...
    nnz(isfinite(LossTailRecords.eta95)));

end



function Out = buildLossTailRecords(curves)
