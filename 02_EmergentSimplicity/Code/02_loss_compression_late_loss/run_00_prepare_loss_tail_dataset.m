for i = 1:numel(curves)
    rec = curves(i);
    record_ID = string(rec.record_ID);

    Dmax = getNumericField(rec, "PeakOutageFraction");
    peakTime = getNumericField(rec, "PeakTime");
    D0 = getNumericField(rec, "D0");
