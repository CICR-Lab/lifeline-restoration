function ensureDir(d)
if ~isfolder(d)
    mkdir(char(d));
end
end

function q = quantileLocal(vals, probs)
vals = sort(vals(:));
vals = vals(isfinite(vals));
if isempty(vals)
    q = nan(size(probs));
    return;
end
q = nan(size(probs));
for i = 1:numel(probs)
    p = probs(i);
    if isscalar(vals)
        q(i) = vals(1);
    else
        pos = 1 + (numel(vals) - 1) * p;
        lo = floor(pos);
        hi = ceil(pos);
        if lo == hi
            q(i) = vals(lo);
        else
            q(i) = vals(lo) + (vals(hi) - vals(lo)) * (pos - lo);
        end
    end
end
end

function s = normalizeSystemName(s)
s = string(s);
sl = lower(strtrim(s));
s(sl == "all systems" | sl == "all" | sl == "pooled") = "All systems";
s(sl == "e" | sl == "power") = "Power";
s(sl == "w" | sl == "water" | sl == "water supply") = "Water";
s(sl == "g" | sl == "gas" | sl == "natural gas") = "Gas";
end

function s = displaySystemName(s)
s = normalizeSystemName(s);
s(s == "Power") = "Electric power";
s(s == "Water") = "Water supply";
s(s == "Gas") = "Natural gas";
end

function g = groupLabel(g)
if g == "All systems"
    g = "All systems";
elseif g == "Power"
    g = "Electric power";
elseif g == "Water"
    g = "Water supply";
elseif g == "Gas"
    g = "Natural gas";
end
end
