function Tail = buildTailLossResults(T, sysOrder)

eta90 = double(T.eta90);
system = normalizeSystemName(T.system);

keep = ...
    ismember(system, sysOrder) & ...
    isfinite(eta90) & ...
    eta90 >= 0;

source = table( ...
    string(T.record_ID(keep)), ...
    system(keep), ...
    eta90(keep), ...
    'VariableNames', { ...
        'record_ID', ...
        'system', ...
        'eta90'});

groups = ["All systems", sysOrder];
summary = emptyTailSummary();

for g = 1:numel(groups)

    if groups(g) == "All systems"
        idx = true(height(source), 1);
    else
        idx = source.system == groups(g);
    end

    values = double(source.eta90(idx));

    q = quantileLocal( ...
        values, ...
        [0.05 0.25 0.50 0.75 0.95]);

    summary = [ ...
        summary
        table( ...
            groupLabel(groups(g)), ...
            nnz(idx), ...
            q(3), ...
            q(2), ...
            q(4), ...
            q(1), ...
            q(5), ...
            'VariableNames', { ...
                'system', ...
                'n', ...
                'median', ...
                'Q25', ...
                'Q75', ...
                'Q05', ...
                'Q95'})];
end

Tail = struct( ...
    "source", source, ...
    "summary", summary);

end

